-- ========================================================
-- SCHEMA SQL: SISTEMA DE CONTROLE E LEMBRETES DE PRAZOS
-- Supabase / PostgreSQL
-- ========================================================

-- 1. Tabela de Membros da Equipe do Escritório
CREATE TABLE IF NOT EXISTS team_members (
    telegram_user_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    username TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE team_members IS 'Armazena os membros da equipe que utilizam o bot (ex: Irmão, Amigo, Chefe).';
COMMENT ON COLUMN team_members.telegram_user_id IS 'ID numérico único do usuário no Telegram (formato texto).';
COMMENT ON COLUMN team_members.name IS 'Nome ou apelido de exibição da pessoa no escritório.';
COMMENT ON COLUMN team_members.username IS 'Username (@usuario) no Telegram, se houver.';

-- 2. Tabela de Processos e Prazos
CREATE TABLE IF NOT EXISTS processes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_number TEXT NOT NULL,
    client_name TEXT NOT NULL,
    deadline_info TEXT NOT NULL,
    owner_telegram_id TEXT NOT NULL,
    owner_name TEXT NOT NULL,
    due_date DATE NOT NULL,
    remind_days_before INT NOT NULL DEFAULT 3,
    status TEXT NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE', 'CONCLUIDO', 'CANCELADO')),
    completed_by TEXT NULL,
    completed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE processes IS 'Prazos processuais cadastrados pela equipe.';
COMMENT ON COLUMN processes.process_number IS 'Número identificador do processo nos autos.';
COMMENT ON COLUMN processes.client_name IS 'Nome do cliente atendido.';
COMMENT ON COLUMN processes.deadline_info IS 'Descrição da tarefa/prazo que vence (ex: Apelação, Réplica, Contestação).';
COMMENT ON COLUMN processes.owner_telegram_id IS 'ID do responsável no Telegram que receberá as cobranças individuais.';
COMMENT ON COLUMN processes.owner_name IS 'Nome do responsável exibido nas listagens.';
COMMENT ON COLUMN processes.due_date IS 'Data fatal de vencimento do prazo (AAAA-MM-DD).';
COMMENT ON COLUMN processes.remind_days_before IS 'Quantos dias de antecedência o bot começará a alertar.';
COMMENT ON COLUMN processes.status IS 'Status atual do prazo: PENDENTE, CONCLUIDO ou CANCELADO.';

-- Índices para otimizar as buscas do cron e listagens
CREATE INDEX IF NOT EXISTS idx_processes_status_due_date ON processes (status, due_date ASC);
CREATE INDEX IF NOT EXISTS idx_processes_owner_status ON processes (owner_telegram_id, status);

-- 3. Tabela de Configurações Gerais da Aplicação
CREATE TABLE IF NOT EXISTS app_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

COMMENT ON TABLE app_settings IS 'Parâmetros dinâmicos do sistema, como o ID do Grupo Geral do Escritório.';

-- Inserção inicial padrão para a chave do grupo geral (caso ainda não configurada)
INSERT INTO app_settings (key, value)
VALUES ('office_group_chat_id', '')
ON CONFLICT (key) DO NOTHING;

-- Configuração de Row Level Security (RLS)
-- Como o bot utiliza a chave de serviço (SUPABASE_SERVICE_ROLE_KEY),
-- o backend tem acesso completo mesmo com RLS ativado.
ALTER TABLE team_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE processes ENABLE ROW LEVEL SECURITY;
ALTER TABLE app_settings ENABLE ROW LEVEL SECURITY;

-- Políticas para permitir leitura e escrita para autenticação via service_role
CREATE POLICY "Allow service_role full access to team_members" ON team_members
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Allow service_role full access to processes" ON processes
    FOR ALL USING (auth.role() = 'service_role');

CREATE POLICY "Allow service_role full access to app_settings" ON app_settings
    FOR ALL USING (auth.role() = 'service_role');
